                <?php if ($step === 'error'): ?>
                    <div class="bg-red-50 border-l-4 border-red-500 p-4 mb-8 rounded-r-lg">
                        <div class="flex items-start">
                            <i class="ph-fill ph-warning-circle text-red-500 text-xl mt-0.5 mr-3"></i>
                            <div>
                                <h3 class="text-red-800 font-bold mb-1">Installation Failed</h3>
                                <ul class="text-red-700 text-sm list-disc pl-4 space-y-1">
                                    <?php foreach ($errors as $err): ?>
                                        <li><?= htmlspecialchars($err) ?></li>
                                    <?php endforeach; ?>
                                </ul>
                            </div>
                        </div>
                    </div>
                <?php endif; ?>

                <?php if ($step === 'success'): ?>
                    <div class="text-center py-6">
                        <div class="w-20 h-20 bg-green-100 text-green-600 rounded-full flex items-center justify-center mx-auto mb-6">
                            <i class="ph-fill ph-check-circle text-5xl"></i>
                        </div>
                        <h2 class="text-3xl font-bold text-gray-900 mb-4">Installation Complete!</h2>
                        <p class="text-lg text-gray-600 mb-8">Your database has been set up with <?= $countOffices ?> offices across <?= $countCountries ?> countries.</p>
                        
                        <div class="bg-amber-50 border border-amber-200 p-6 rounded-2xl mb-8">
                            <div class="flex items-start gap-4 text-left">
                                <i class="ph-fill ph-warning text-amber-500 text-3xl"></i>
                                <div>
                                    <h3 class="font-bold text-amber-900 mb-1">Security Warning</h3>
                                    <p class="text-amber-800 text-sm">For security reasons, please DELETE the <strong>install.php</strong> file from your server immediately!</p>
                                </div>
                            </div>
                        </div>

                        <a href="/" class="inline-block bg-[#0c2d74] text-white hover:bg-[#1a4ba0] font-semibold py-4 px-10 rounded-xl transition-colors text-lg shadow-md">
                            Go to Homepage
                        </a>
                    </div>
                <?php else: ?>
                    <form method="POST" action="install.php" class="space-y-6">
                        <input type="hidden" name="csrf_token" value="<?= htmlspecialchars($_SESSION['csrf_token']) ?>">
                        
                        <div class="grid grid-cols-1 md:grid-cols-2 gap-6">
                            <div>
                                <label class="block text-sm font-semibold text-gray-700 mb-2">Database Host</label>
                                <input type="text" name="db_host" value="<?= htmlspecialchars($_POST['db_host'] ?? 'localhost') ?>" class="w-full px-4 py-3 rounded-xl border border-gray-300 focus:border-[#0c2d74] focus:ring-1 focus:ring-[#0c2d74] outline-none">
                            </div>
                            <div>
                                <label class="block text-sm font-semibold text-gray-700 mb-2">Database Port</label>
                                <input type="text" name="db_port" value="<?= htmlspecialchars($_POST['db_port'] ?? '3306') ?>" class="w-full px-4 py-3 rounded-xl border border-gray-300 focus:border-[#0c2d74] focus:ring-1 focus:ring-[#0c2d74] outline-none">
                            </div>
                        </div>

                        <div>
                            <label class="block text-sm font-semibold text-gray-700 mb-2">Database Name <span class="text-red-500">*</span></label>
                            <input type="text" name="db_name" value="<?= htmlspecialchars($_POST['db_name'] ?? 'asg_offices') ?>" required class="w-full px-4 py-3 rounded-xl border border-gray-300 focus:border-[#0c2d74] focus:ring-1 focus:ring-[#0c2d74] outline-none">
                            <p class="text-xs text-gray-500 mt-1">The database will be created if it doesn't exist (requires sufficient privileges).</p>
                        </div>

                        <div class="grid grid-cols-1 md:grid-cols-2 gap-6">

<?php
/**
 * Acıbadem International Offices — Installation Wizard
 * This file sets up the database and configuration.
 * DELETE THIS FILE after successful installation!
 */
session_start();

// Check if already installed
if (file_exists(__DIR__ . '/config.php')) {
    require_once __DIR__ . '/config.php';
    if (defined('APP_INSTALLED') && APP_INSTALLED) {
        header('Location: index.php');
        exit;
    }
}

$step = 'form'; // form, processing, success, error
$errors = [];
$success = false;

// CSRF token
if (empty($_SESSION['csrf_token'])) {
    $_SESSION['csrf_token'] = bin2hex(random_bytes(32));
}

$countOffices = 0;
$countCountries = 0;

if ($_SERVER['REQUEST_METHOD'] === 'POST') {
    // Verify CSRF
    if (!hash_equals($_SESSION['csrf_token'], $_POST['csrf_token'] ?? '')) {
        $errors[] = 'Invalid security token. Please try again.';
    } else {
        $dbHost = trim($_POST['db_host'] ?? 'localhost');
        $dbPort = trim($_POST['db_port'] ?? '3306');
        $dbName = trim($_POST['db_name'] ?? 'asg_offices');
        $dbUser = trim($_POST['db_user'] ?? '');
        $dbPass = $_POST['db_pass'] ?? '';
        $appUrl = rtrim(trim($_POST['app_url'] ?? ''), '/');
        
        // Validate
        if (empty($dbName)) $errors[] = 'Database name is required.';
        if (empty($dbUser)) $errors[] = 'Database username is required.';
        
        if (empty($errors)) {
            try {
                // Test connection
                $dsn = "mysql:host={$dbHost};port={$dbPort};charset=utf8mb4";
                $pdo = new PDO($dsn, $dbUser, $dbPass, [
                    PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION
                ]);
                
                // Create database if not exists
                $pdo->exec("CREATE DATABASE IF NOT EXISTS `" . str_replace('`', '``', $dbName) . "` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci");
                $pdo->exec("USE `" . str_replace('`', '``', $dbName) . "`");
                
                // Run schema
                $schemaFile = __DIR__ . '/database/schema.sql';
                if (file_exists($schemaFile)) {
                    $schema = file_get_contents($schemaFile);
                    if ($schema) {
                        $pdo->exec($schema);
                    }
                } else {
                    $errors[] = "Schema file not found at $schemaFile";
                }
                
                // Run seed data
                $seedFile = __DIR__ . '/database/seed.sql';
                if (file_exists($seedFile)) {
                    $seed = file_get_contents($seedFile);
                    if ($seed) {
                        // Split by semicolons and execute each statement
                        $statements = array_filter(array_map('trim', explode(';', $seed)));
                        foreach ($statements as $stmt) {
                            if (!empty($stmt) && stripos($stmt, 'INSERT') !== false) {
                                $pdo->exec($stmt);
                            } elseif (!empty($stmt) && stripos($stmt, 'SET') !== false) {
                                $pdo->exec($stmt);
                            }
                        }
                    }
                } else {
                    $errors[] = "Seed file not found at $seedFile";
                }
                
                if (empty($errors)) {
                    // Try to get counts
                    try {
                        $countOffices = $pdo->query("SELECT count(*) FROM offices")->fetchColumn();
                        $countCountries = $pdo->query("SELECT count(DISTINCT country) FROM offices")->fetchColumn();
                    } catch (Exception $e) {
                        // Ignore
                    }
                    
                    // Generate config.php
                    $appSecret = bin2hex(random_bytes(32));
                    $configContent = "<?php\n";
                    $configContent .= "// Auto-generated by installer on " . date('Y-m-d H:i:s') . "\n";
                    $configContent .= "// WARNING: This file contains sensitive credentials. Keep it secure!\n\n";
                    $configContent .= "define('DB_HOST', " . var_export($dbHost, true) . ");\n";
                    $configContent .= "define('DB_PORT', " . var_export($dbPort, true) . ");\n";
                    $configContent .= "define('DB_NAME', " . var_export($dbName, true) . ");\n";
                    $configContent .= "define('DB_USER', " . var_export($dbUser, true) . ");\n";
                    $configContent .= "define('DB_PASS', " . var_export($dbPass, true) . ");\n";
                    $configContent .= "define('APP_SECRET', " . var_export($appSecret, true) . ");\n";
                    $configContent .= "define('APP_URL', " . var_export($appUrl, true) . ");\n";
                    $configContent .= "define('APP_INSTALLED', true);\n";
                    
                    if (file_put_contents(__DIR__ . '/config.php', $configContent) === false) {
                        $errors[] = 'Could not write config.php. Please check file permissions on the root directory.';
                    } else {
                        $success = true;
                        $step = 'success';
                    }
                }
            } catch (PDOException $e) {
                $errors[] = 'Database error: ' . $e->getMessage();
            }
        }
    }
    
    if (!empty($errors)) {
        $step = 'error';
    }
}
